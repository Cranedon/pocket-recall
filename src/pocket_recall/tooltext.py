"""Text that Claude Code and the user's tools put into the user's turn, and taking it out.

A transcript's user turns hold more than what the user typed: shell commands run from the app
with their whole output (<bash-input>, <bash-stdout>), the state of an open artifact, background
task notifications, and sentences the app writes ("I hit my usage limit … it has reset now").
Stored as the user's words they crowd recall, and as prompts they set off injection. Both the
importer and the injection hook pass user text through `strip_tool_text`.

    pocket-recall clean DB [--dry-run]   take tool text out of a store written before 0.3.1

Only the standard library is imported here, so the injection hook stays fast.
"""

from __future__ import annotations

import re

# Blocks whose whole content is tool output or app state, never something the user wrote.
_BLOCKS = re.compile(
    r"<(bash-input|bash-stdout|bash-stderr|system-reminder|task-notification|scheduled-task|"
    r"local-command-[a-z]+|command-[a-z]+|artifact-view-context)\b[^>]*>.*?</\1>", re.S)
_SELF_CLOSING = re.compile(r"<artifact-content-authored-by-others\s*/>")
# Sentences the app types into the user's turn.
_APP_LINES = re.compile(
    r"^[ \t]*(\[(?:Request interrupted by user|Usage limit reached|Earlier usage)[^\]\n]*\]|"
    r"I hit my usage limit while you were working, but it has reset now\.[^\n]*|"
    r"在您工作期间，我达到了使用限额，但现在限额已重置。[^\n]*|"
    r"Caveat: The messages below were generated by the user while running local commands\.[^\n]*)[ \t]*$", re.M)
# Still starting with a tag once the known blocks are gone: a tool message of a kind not listed above.
# The user's own pastes arrive wrapped in <pasted_content> and are kept.
_UNKNOWN_TAG = re.compile(r"^\s*<(?!pasted_content)[a-z][a-z0-9_-]*(\s[^>]*)?/?>")
_SUMMARY = ("This session is being continued", "The summarized conversation")


def strip_tool_text(text: str) -> str:
    """What the user wrote in `text`, or "" if it is all tool text."""
    out = _APP_LINES.sub("", _SELF_CLOSING.sub("", _BLOCKS.sub("", text)))
    if out != text:  # close the gaps left behind; the user's own text keeps its blank lines
        out = re.sub(r"\n{3,}", "\n\n", out)
    out = out.strip()
    if _UNKNOWN_TAG.match(out) or out.startswith(_SUMMARY):
        return ""
    return out


def main() -> None:
    """pocket-recall clean DB: take tool output and app messages out of stored user turns."""
    import argparse

    from .store import MemoryStore

    p = argparse.ArgumentParser(prog="pocket-recall clean", description=main.__doc__)
    p.add_argument("db")
    p.add_argument("--dry-run", action="store_true", help="only count what would change")
    args = p.parse_args()
    store = MemoryStore(args.db, scorer="bm25")
    changed, deleted = store.clean_tool_text(dry_run=args.dry_run)
    verb = "would change" if args.dry_run else "changed"
    print(f"{verb} {changed} user messages and {'would delete' if args.dry_run else 'deleted'} {deleted} "
          "that held only tool text")
    store.close()
